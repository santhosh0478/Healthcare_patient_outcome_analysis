# 6. Interventions
# ----------------------------------------------------------------------------
with tab_int:
    st.write("We use the fitted model to ask \"what if\" questions: set `followup_7d = 1` for some "
             "patients and see how the predicted readmission rate changes.")
    st.warning("These are model-based estimates on synthetic data. They assume the follow-up effect "
               "is causal. A real hospital would confirm it with a pilot or trial.")

    top_pct = st.slider("Target the top X% highest-risk patients (scenarios B and C)", 5, 50, 20, 5)
    attend = st.slider("Share of targeted patients who attend (scenario C)", 10, 100, 50, 10)

    base_rate = base_p.mean()


    def scenario(mask):
        d2 = df.copy()
        d2.loc[mask, "followup_7d"] = 1
        return model.predict(d2).mean()


    rate_a = scenario(np.ones(len(df), dtype=bool))
    thr = base_p.quantile(1 - top_pct / 100)
    mask_b = ((base_p >= thr) & (df["followup_7d"] == 0)).values
    rate_b = scenario(mask_b)
    rng2 = np.random.default_rng(11)
    mask_c = mask_b & (rng2.random(len(df)) < attend / 100)
    rate_c = scenario(mask_c)

    rows = []
    for name, rate, reached in [
        ("A: follow-up for everyone", rate_a, int((df["followup_7d"] == 0).sum())),
        (f"B: follow-up for top {top_pct}% high-risk", rate_b, int(mask_b.sum())),
        (f"C: same as B, {attend}% attend", rate_c, int(mask_c.sum())),
    ]:
        rows.append({
            "scenario": name,
            "patients_reached": reached,
            "new_readmit_rate_%": round(rate * 100, 2),
            "relative_reduction_%": round((base_rate - rate) / base_rate * 100, 1),
            "readmissions_avoided": round((base_rate - rate) * len(df)),
        })
    st.metric("Baseline readmission rate (model)", f"{base_rate:.2%}")
    st.dataframe(pd.DataFrame(rows), width="stretch")

    obs = df.groupby("followup_7d")["readmitted"].mean()
    st.write(f"**Observed in the data:** no follow-up {obs[0]:.2%} vs follow-up {obs[1]:.2%} "
             f"({(obs[0] - obs[1]) / obs[0]:.1%} relative difference).")

