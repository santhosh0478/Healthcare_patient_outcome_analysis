overall = d["readmitted"].mean() * 100


def rate_chart(col, title, color, order=None):
    r = d.groupby(col)["readmitted"].mean() * 100
    if order is not None:
        r = r.reindex([o for o in order if o in r.index])
    else:
        r = r.sort_values(ascending=False)
    fig = go.Figure(go.Bar(x=r.index, y=r.values, marker_color=color))
    fig.add_hline(y=overall, line_dash="dash", annotation_text="overall")
    fig.update_layout(title=title, yaxis_title="Readmission rate (%)", height=380,
                      margin=dict(t=50, b=10))
    return fig


with tab_over:
    left, right = st.columns(2)
    left.plotly_chart(rate_chart("diagnosis", "Readmission Rate by Diagnosis", "#2563eb"), width="stretch")
    right.plotly_chart(rate_chart("age_group", "Readmission Rate by Age Group", "#f97316", age_opts),
                       width="stretch")
    left, right = st.columns(2)
    left.plotly_chart(rate_chart("followup_label", "Follow-up vs No Follow-up", "#16a34a"), width="stretch")
    right.plotly_chart(rate_chart("prior_group", "Readmission Rate by Prior Admissions", "#dc2626",
                                  ["0", "1", "2", "3", "4+"]), width="stretch")

    fig = go.Figure()
    fig.add_trace(go.Histogram(x=d.loc[d["readmitted"] == 0, "length_of_stay"], histnorm="probability density",
                               name="Not readmitted", opacity=0.6))
    fig.add_trace(go.Histogram(x=d.loc[d["readmitted"] == 1, "length_of_stay"], histnorm="probability density",
                               name="Readmitted", opacity=0.6))
    fig.update_layout(barmode="overlay", title="Length of Stay: Readmitted vs Not",
                      xaxis_title="Days", height=380, margin=dict(t=50, b=10))
    st.plotly_chart(fig, width="stretch")

# ----------------------------------------------------------------------------
# 5. Risk factors (uses all patients so results are stable)
# ----------------------------------------------------------------------------
with tab_risk:
    st.write("These results use **all patients** (not only the filtered ones).")

    st.subheader("Correlation with 30-day readmission")
    numeric = ["age", "prior_admissions", "comorbidity_count", "length_of_stay",
               "num_medications", "num_lab_procedures", "bmi", "systolic_bp", "followup_7d"]
    rows = []
    for c in numeric:
        r, p = stats.pearsonr(df[c], df["readmitted"])
        rows.append({"factor": c, "correlation": r, "p_value": p})
    corr_df = pd.DataFrame(rows).sort_values("correlation")
    fig = go.Figure(go.Bar(x=corr_df["correlation"], y=corr_df["factor"], orientation="h",
                           marker_color=["#dc2626" if v > 0 else "#16a34a" for v in corr_df["correlation"]]))
    fig.update_layout(height=380, margin=dict(t=20, b=10))
    st.plotly_chart(fig, width="stretch")

    st.subheader("Chi-square tests (categorical factors)")
    chi_rows = []
    for c in ["diagnosis", "insurance", "discharge_disposition", "followup_7d", "gender"]:
        table = pd.crosstab(df[c], df["readmitted"])
        chi2, p, _, _ = stats.chi2_contingency(table)
        v = np.sqrt(chi2 / (table.values.sum() * (min(table.shape) - 1)))
        chi_rows.append({"factor": c, "chi2": round(chi2, 2), "p_value": p, "cramers_v": round(v, 3)})
    st.dataframe(pd.DataFrame(chi_rows).sort_values("cramers_v", ascending=False), width="stretch")

    st.subheader("Logistic regression: odds ratios")
    st.caption("Odds ratio above 1 = higher readmission risk. Below 1 = lower risk. "
               "The model looks at all factors together.")
    ci = model.conf_int()
    or_df = pd.DataFrame({
        "factor": [nice(n) for n in model.params.index],
        "odds_ratio": np.exp(model.params.values),
        "ci_low": np.exp(ci[0].values),
        "ci_high": np.exp(ci[1].values),
        "p_value": model.pvalues.values,
    }).query("factor != 'Intercept'").sort_values("odds_ratio", ascending=False)
    or_df["significant"] = or_df["p_value"] < 0.05
    st.dataframe(or_df.round(3), width="stretch")

    plot_df = or_df.sort_values("odds_ratio")
    fig = go.Figure(go.Bar(x=plot_df["odds_ratio"], y=plot_df["factor"], orientation="h",
                           marker_color=["#dc2626" if v > 1 else "#16a34a" for v in plot_df["odds_ratio"]]))
    fig.add_vline(x=1, line_color="black")
    fig.update_layout(height=560, margin=dict(t=20, b=10), xaxis_title="Odds ratio")
    st.plotly_chart(fig, width="stretch")

